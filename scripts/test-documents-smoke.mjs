#!/usr/bin/env node

const baseUrl = process.env.OPENCLAW_API_URL || 'http://127.0.0.1:8080';
const now = Date.now();
const username = `docsmoke_${now}`;
const password = 'DocumentSmoke123!';
const email = `${username}@example.test`;

async function request(method, path, { token, botKey, body, expect = [200] } = {}) {
  const headers = { Accept: 'application/json' };
  if (token) headers.Authorization = `Bearer ${token}`;
  if (botKey) headers['X-Bot-Key'] = botKey;
  if (body !== undefined) headers['Content-Type'] = 'application/json';

  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let json = null;
  if (text) {
    try {
      json = JSON.parse(text);
    } catch (error) {
      throw new Error(`${method} ${path} returned non-JSON body: ${text}`);
    }
  }
  if (!expect.includes(response.status)) {
    throw new Error(`${method} ${path} returned ${response.status}, expected ${expect.join('/')} body=${text}`);
  }
  return { status: response.status, json };
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

async function main() {
  console.log(`[documents-smoke] backend=${baseUrl}`);

  const health = await request('GET', '/health', { expect: [200] });
  assert(health.json?.status === 'ok', 'health endpoint did not report ok');

  const register = await request('POST', '/api/v1/auth/register', {
    expect: [201],
    body: { username, email, password },
  });
  const token = register.json?.data?.tokens?.access_token;
  const userID = register.json?.data?.user?.id;
  assert(token, 'register response did not include access token');
  assert(userID, 'register response did not include user id');

  const created = await request('POST', '/api/v1/documents', {
    token,
    expect: [201],
    body: {
      title: 'Smoke Document',
      body: '# Smoke Document\n\nCreated through the user document API.',
      summary: 'User-created smoke document',
    },
  });
  const doc = created.json?.data;
  assert(doc?.id, 'document create response missing id');
  assert(doc.url === `/documents/${doc.id}`, `document url mismatch: ${doc.url}`);
  assert(doc.body.includes('user document API'), 'document create response missing body');

  const list = await request('GET', '/api/v1/documents', { token });
  assert(Array.isArray(list.json?.data), 'document list response is not an array');
  assert(list.json.data.some((item) => item.id === doc.id), 'created document not found in list');
  const listed = list.json.data.find((item) => item.id === doc.id);
  assert(!listed.body, 'document list should not include full body');

  const updated = await request('PUT', `/api/v1/documents/${doc.id}`, {
    token,
    body: { title: 'Smoke Document Updated', body: '# Smoke Document Updated\n\nPersisted edit.' },
  });
  assert(updated.json?.data?.title === 'Smoke Document Updated', 'document update did not persist title');
  assert(updated.json?.data?.body.includes('Persisted edit'), 'document update did not persist body');

  const bot = await request('POST', '/api/v1/bots', {
    token,
    expect: [201],
    body: { name: 'Document Smoke Bot', bot_type: 'assistant' },
  });
  const botID = bot.json?.data?.id;
  assert(botID, 'bot create response missing id');

  const key = await request('POST', `/api/v1/bots/${botID}/keys`, {
    token,
    expect: [201],
    body: { name: 'documents smoke key' },
  });
  const botKey = key.json?.data?.key;
  assert(botKey, 'bot key response missing plaintext key');

  const conversationID = `chat/dm/user/${userID}/bot/${botID}`;
  const botCreate = await request('POST', '/api/v1/bot-runtime/documents', {
    botKey,
    expect: [201],
    body: {
      title: 'Bot Smoke Document',
      body: '# Bot Smoke Document\n\nGenerated by bot runtime.',
      conversation_id: conversationID,
      send_url: true,
    },
  });
  const botDoc = botCreate.json?.data?.document;
  const createMessage = botCreate.json?.data?.message;
  assert(botDoc?.source === 'bot', 'bot-created document should have source=bot');
  assert(botDoc?.url === `/documents/${botDoc.id}`, 'bot-created document url mismatch');
  assert(createMessage?.msg_type === 'text', `bot create message type = ${createMessage?.msg_type}, want text`);
  assert(createMessage?.content?.body?.includes(`/documents/${botDoc.id}`), 'bot create message body missing document URL');
  assert(createMessage?.metadata?.document_url === `/documents/${botDoc.id}`, 'bot create message metadata missing document_url');
  assert(createMessage?.metadata?.document_title === 'Bot Smoke Document', 'bot create message metadata missing document_title');
  assert(createMessage?.metadata?.document_summary !== undefined, 'bot create message metadata missing document_summary');
  assert(createMessage?.metadata?.document_type === 'markdown', 'bot create message metadata missing document_type');
  assert(createMessage?.metadata?.document_updated_at, 'bot create message metadata missing document_updated_at');

  const botUpdate = await request('PUT', `/api/v1/bot-runtime/documents/${botDoc.id}`, {
    botKey,
    body: {
      title: 'Bot Smoke Document Updated',
      body: '# Bot Smoke Document Updated\n\nEdited by bot runtime.',
      conversation_id: conversationID,
      send_url: true,
    },
  });
  const updateMessage = botUpdate.json?.data?.message;
  assert(botUpdate.json?.data?.document?.title === 'Bot Smoke Document Updated', 'bot update did not persist title');
  assert(updateMessage?.msg_type === 'text', `bot update message type = ${updateMessage?.msg_type}, want text`);
  assert(updateMessage?.content?.body?.includes(`/documents/${botDoc.id}`), 'bot update message body missing document URL');
  assert(updateMessage?.metadata?.document_title === 'Bot Smoke Document Updated', 'bot update message metadata missing updated document_title');

  const messages = await request('GET', `/api/v1/messages?conversation_id=${encodeURIComponent(conversationID)}&limit=20`, {
    token,
  });
  const messageItems = messages.json?.data || [];
  assert(Array.isArray(messageItems), 'messages response is not an array');
  const documentMessages = messageItems.filter((item) => item.metadata?.document_id === botDoc.id);
  assert(documentMessages.length >= 2, `expected at least 2 document URL messages, got ${documentMessages.length}`);
  assert(documentMessages.every((item) => item.msg_type === 'text' && item.content?.type === 'text'), 'document URL messages must be plain text');

  const archive = await request('DELETE', `/api/v1/documents/${doc.id}`, { token });
  assert(archive.json?.code === 0, 'archive response code was not success');
  const archivedGet = await request('GET', `/api/v1/documents/${doc.id}`, { token, expect: [404] });
  assert(archivedGet.json?.code === 404, 'archived document should return not found');

  console.log('[documents-smoke] PASS');
  console.log(JSON.stringify({
    user_id: userID,
    bot_id: botID,
    user_document_url: doc.url,
    bot_document_url: botDoc.url,
    conversation_id: conversationID,
  }, null, 2));
}

main().catch((error) => {
  console.error('[documents-smoke] FAIL');
  console.error(error.stack || error.message);
  process.exit(1);
});
